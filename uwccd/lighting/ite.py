VID = 0x048D
KB_PIDS = [0xCE00, 0x6000, 0x6001, 0x6002, 0x6003, 0x6004, 0x6006, 0x6007, 0x600A]
LB_PIDS = [0x7000, 0x6005, 0x6008, 0x6010]

# LightingModel.RGBKB_Effect -> ITE effect code (Translate_ITE_EffectIndex)
EFFECTS = {
    0: ("Single", 0x01), 1: ("Breathing", 0x02), 2: ("Wave", 0x03), 3: ("Reactive", 0x04),
    4: ("Rainbow", 0x05), 5: ("Ripple", 0x06), 6: ("Raindrop", 0x0A), 7: ("Neon", 0x0F),
    8: ("Marquee", 0x09), 9: ("Stack", 0x0C), 10: ("Impact", 0x0D), 11: ("Spark", 0x11),
    12: ("Aurora", 0x0E), 13: ("Music", 0x22), 14: ("UserMode", 0x33), 15: ("Gaming", 0x15),
    16: ("Flash", 0x12), 17: ("Mix", 0x13), 18: ("RippleO", 0x16), 20: ("Alphabet", 0x17),
    21: ("StarHitting", 0x19), 22: ("StarSpark", 0x18), 23: ("Thinking", 0x21), 26: ("ColorfulWave", 0x34),
}
LIGHT = [0, 8, 0x16, 0x24, 0x32]          # Translate_ITE_LightValue (0..4)
SPEED = [0x0A, 7, 5, 3, 1]                # Translate_ITE_SpeedValue (0..4, slow..fast)
DIRECTION = {-1: 0, 0: 1, 1: 2, 2: 3, 3: 4, 4: 1, 5: 3}
DEFAULT_COLORS = [(255, 0, 0), (255, 165, 0), (255, 255, 0), (0, 255, 0), (0, 0, 255), (0, 127, 255), (139, 0, 255)]

# software-driven (AP) effects of GCUService (frames generated by the service, see apfx.py)
AP_EFFECTS = {0x0C, 0x0D, 0x0F, 0x17}
# lightbar-only AP effects (nothing is drawn on a keyboard by GCUService)
LB_ONLY_EFFECTS = {0x18, 0x19}

ME_3ND = {0x11, 0x12}
ME_2P1ND = {7, 8, 9, 0xA}
ME_2P2ND = {0xD, 0xE, 0xF, 0x10}
ME_LIGHTBAR = {0xC, 0x13, 0x14, 0x15}

ROWS, COLS = 6, 21

# Reactive effects light the pressed key: the EC has to pass key presses to the ITE controller
# (LM_ITE_RGB.Enable_EC_OnkeyPressed: EC 0x741 bit 3, for Reactive, Ripple, Aurora, Spark with direction code 1)
REACTIVE = {0x04, 0x06, 0x0E, 0x11}
REG_ONKEY, ONKEY_BIT = 0x741, 3
# A repeated identical request (double click) within this time is dropped, and two effect changes are kept at
# least MIN_GAP apart: the controller is still rolling out the previous effect across its LED zones.
REPEAT_WINDOW, MIN_GAP = 0.6, 0.15
# Four-zone keyboards (kb_type 2/3, RGBKB_Type.FourZone): the original window (CCU.WinUI 5.56,
# MyKeyboardTypeInfo.InitalizeKeyboardTypeEffect) offers exactly Single, Breathing, Wave, Rainbow, Flash and Mix there,
# and these are the ones that work on MAIBENBEN Tsunami (ITE 11.5). Rainbow is a still rainbow on ITE firmware.
FOUR_ZONE_CHECKED = {0x01, 0x02, 0x03, 0x05, 0x12, 0x13}
FOUR_ZONE_EFFECTS = set(FOUR_ZONE_CHECKED)
# drawn by the service, zone by zone, with smooth transitions: Stack, Impact, Neon (frames of the original, averaged
# per zone and blended), Colour wave and Wave (colours flowing across the zones), Flash (fading flashes)
FOUR_ZONE_SOFT = {0x0C, 0x0D, 0x0F, 0x34}
# columns of the 6 x 21 key grid per zone: three on the main block, the fourth on the numeric pad
ZONE_COLS = ((0, 6), (6, 12), (12, 17), (17, 21))


def _ioc(d, t, nr, size):
    return (d << 30) | (size << 16) | (ord(t) << 8) | nr


def HIDIOCSFEATURE(n):
    return _ioc(3, "H", 0x06, n)


def HIDIOCGFEATURE(n):
    return _ioc(3, "H", 0x07, n)


def _usage_page(desc):
    i = 0
    while i < len(desc):
        b = desc[i]
        size = {0: 0, 1: 1, 2: 2, 3: 4}[b & 3]
        if b & 0xFC == 0x04:  # Usage Page
            return int.from_bytes(desc[i + 1:i + 1 + size], "little")
        i += 1 + size
    return None


class HidrawTransport:
    """Linux /dev/hidrawN: feature reports via HIDIOC[SG]FEATURE, output reports via write()."""

    def __init__(self, dev):
        self.fd = os.open(dev["node"], os.O_RDWR | os.O_CLOEXEC)

    def feature(self, data):
        fcntl.ioctl(self.fd, HIDIOCSFEATURE(len(data)), bytes(data))

    def get_feature(self, size=9):
        buf = bytearray(size)
        fcntl.ioctl(self.fd, HIDIOCGFEATURE(size), buf, True)
        return buf

    def output(self, data):
        os.write(self.fd, bytes(data))

    def close(self):
        try:
            os.close(self.fd)
        except OSError:
            pass


def open_transport(dev):
    if sys.platform == "win32":
        from ..win.hid import WinHidTransport
        return WinHidTransport(dev)
    return HidrawTransport(dev)


def find_devices(pids):
    if sys.platform == "win32":
        from ..win.hid import enumerate_devices
        return enumerate_devices(VID, pids)
    out = []
    for hr in sorted(glob.glob("/sys/class/hidraw/hidraw*")):
        try:
            uevent = open(os.path.join(hr, "device", "uevent")).read()
        except OSError:
            continue
        hid_id = next((ln.split("=", 1)[1] for ln in uevent.splitlines() if ln.startswith("HID_ID=")), "")
        parts = hid_id.split(":")
        if len(parts) != 3:
            continue
        vid, pid = int(parts[1], 16), int(parts[2], 16)
        if vid != VID or (pids is not None and pid not in pids):
            continue
        try:
            desc = open(os.path.join(hr, "device", "report_descriptor"), "rb").read()
        except OSError:
            desc = b""
        out.append({"node": "/dev/" + os.path.basename(hr), "pid": pid, "usage_page": _usage_page(desc)})
    return out


class APEngine(threading.Thread):
    """LM_ITE_RGB.AP_Effect_Task — runs the generated frame program until stopped."""

    def __init__(self, kb, effect, light, speed, colors, alphabet):
        super().__init__(daemon=True, name="ap-effect")
        self.kb = kb
        self.effect, self.light, self.speed = effect, light, speed
        self.kb_type = kb.kb_type
        cols = list(colors or []) + DEFAULT_COLORS
        self.colors = [apfx.RGB(*c) for c in cols[:7]]
        self.alphabet = alphabet or "HELLO"
        self._halt = threading.Event()
        self._target = None             # four zones: the latest frame; a blender thread eases towards it
        self._blender = None

    def stop(self):
        self._halt.set()
        if self._blender and self._blender is not threading.current_thread():
            self._blender.join(timeout=1)

    def stopped(self):
        return self._halt.is_set()

    def sleep(self, ms):
        return not self._halt.wait(max(1, ms) / 1000.0)

    # four zones: the frames of the per-key effects are averaged per zone and blended over ~0.15 s, so the zones
    # change smoothly instead of jumping from frame to frame
    BLEND_STEP, BLEND_RATE = 0.03, 0.22

    def _zones(self, cols):
        self._target = [tuple(c) for c in cols]
        if self._blender is None:
            self._blender = threading.Thread(target=self._blend, daemon=True, name="ap-blend")
            self._blender.start()

    def _blend(self):
        cur, first = None, True
        try:
            while not self._halt.is_set():
                tgt = self._target
                if tgt is not None:
                    cur = [list(t) for t in tgt] if cur is None else \
                        [[c + (t - c) * self.BLEND_RATE for c, t in zip(cz, tz)] for cz, tz in zip(cur, tgt)]
                    if not self._halt.is_set():
                        self.kb.write_zones([tuple(int(round(v)) for v in z) for z in cur], self.light, announce=first)
                        first = False
                self._halt.wait(self.BLEND_STEP)
        except OSError as e:
            log.warning("software effect stopped: %s", e)

    def user_mode(self, buf, first):
        if self.stopped():
            return
        if self.kb.four_zone():
            self._zones(zones_of([c.t() for c in buf]))
        else:
            self.kb.write_rows([c.t() for c in buf], self.light, 0, announce=bool(first))

    def static_mode(self, c, first):
        if self.stopped():
            return
        if self.kb.four_zone():
            self._zones([c.t()] * 4)
        else:
            self.kb.write_static(c.t(), self.light, 0, announce=bool(first))

    def run(self):
        try:
            apfx.run(self)
        except OSError as e:
            log.warning("software effect stopped: %s", e)


def _fx_env_default():
    return {"config": fxmod.clean_config(None), "ac": True, "metrics": {}}


def zones_of(frame):
    """6 x 21 frame (row 0 = top) -> average colour of each of the four zones (black keys ignored)."""
    out = []
    for c0, c1 in ZONE_COLS:
        px = [frame[r * COLS + c] for r in range(ROWS) for c in range(c0, c1)]
        lit = [p for p in px if any(p)] or px
        out.append(tuple(sum(p[i] for p in lit) // len(lit) for i in range(3)))
    return out


class ZoneWave(threading.Thread):
    """Smooth wave for four-zone keyboards, drawn by the service: the colours flow from zone to zone.
    colors=None: the full hue circle (Colour wave); otherwise the palette, blended (Wave)."""

    def __init__(self, kb, light, speed, colors=None, reverse=False):
        super().__init__(daemon=True, name="zone-wave")
        self.kb, self.light = kb, light
        self.period = (14, 10, 7, 5, 3)[max(0, min(4, speed))]      # seconds per full colour circle
        self.colors = [tuple(c) for c in colors] if colors and len(colors) > 1 else None
        self.reverse = reverse
        self._halt = threading.Event()

    def stop(self):
        self._halt.set()

    def colour_at(self, pos):
        """pos 0..1 on the colour circle"""
        if not self.colors:
            import colorsys
            r, g, b = colorsys.hsv_to_rgb(pos % 1.0, 1.0, 1.0)
            return (int(r * 255), int(g * 255), int(b * 255))
        n = len(self.colors)
        x = (pos % 1.0) * n
        i, f = int(x) % n, x - int(x)
        a, b = self.colors[i], self.colors[(i + 1) % n]
        return tuple(int(a[k] + (b[k] - a[k]) * f) for k in range(3))

    def frame(self, t):
        ph = t / self.period
        step = -0.12 if self.reverse else 0.12
        return [self.colour_at(ph + z * step) for z in range(4)]

    def run(self):
        t0, first = time.monotonic(), True
        try:
            while not self._halt.is_set():
                self.kb.write_zones(self.frame(time.monotonic() - t0), self.light, announce=first)
                first = False
                self._halt.wait(0.04)
        except OSError as e:
            log.warning("zone effect stopped: %s", e)


class ZoneFlash(ZoneWave):
    """Flash for four-zone keyboards: each palette colour fades in and out in turn (the firmware Flash on FF12
    keyboards switches hard on and off). Several colours: one after another; one colour: it keeps pulsing."""

    def __init__(self, kb, light, speed, colors=None, reverse=False):
        super().__init__(kb, light, speed, colors=colors, reverse=reverse)
        self.name = "zone-flash"
        self.palette = [tuple(c) for c in colors] if colors else list(DEFAULT_COLORS)
        self.pulse = (2.0, 1.5, 1.1, 0.8, 0.55)[max(0, min(4, speed))]     # seconds per flash

    def frame(self, t):
        import math
        n = int(t / self.pulse)
        level = math.sin(math.pi * ((t / self.pulse) % 1.0)) ** 2           # smooth 0 -> 1 -> 0
        c = self.palette[n % len(self.palette)]
        return [tuple(int(v * level) for v in c)] * 4


class ITEKeyboard:
    def __init__(self, ec, dev):
        self.ec = ec
        self.node = dev["node"]
        self.pid = dev["pid"]
        self.usage_page = dev["usage_page"]
        self.io = open_transport(dev)
        self.lock = threading.RLock()
        self.project = ec.read(0x740)
        self.ver = (0, 0, 0, 0)
        self.kb_type = 0
        self.saved = None          # last effect (for power on)
        self.ap = None
        self._last_apply = 0.0
        self.pictures_ok = True    # False: the firmware ignores 12h/16h pictures (setting kb_picture_modes off)
        self._onkey = False
        self.fx_env = _fx_env_default    # BetterRGB effects: settings, power source and metrics (set by KeyboardManager)
        self._detect()

    # -- low level -------------------------------------------------------------------
    def feature(self, data):
        buf = bytes(data) + bytes(max(0, 9 - len(data)))
        if log.isEnabledFor(logging.DEBUG):
            log.debug("HID %04x feature %s", self.pid, buf.hex(" "))
        with self.lock:
            self.io.feature(buf)
        time.sleep(0.001)

    def get_feature(self):
        with self.lock:
            return self.io.get_feature(9)

    def output(self, data):
        if log.isEnabledFor(logging.DEBUG):
            log.debug("HID %04x output %d bytes %s…", self.pid, len(data), bytes(data[:16]).hex(" "))
        with self.lock:
            self.io.output(data)

    def cmd08(self, ctrl, effect=0, speed=0, light=0, color=0, direction=0, save=0):
        self.feature([0, 0x08, ctrl, effect, speed, light, color, direction, save])

    def cmd09(self, level):
        self.feature([0, 0x09, 0x02, level])

    def cmd12(self, save=0):
        self.feature([0, 0x12, 0, 0, 0x08, 0, 0, 0, save])

    def cmd14(self, index, r, g, b, flag=0, extra=0):
        r, g, b = self.correct(r, g, b)
        self.feature([0, 0x14, flag, index, r, g, b, extra, 0])

    def firmware_version(self):
        for _ in range(10):
            self.feature([0, 0x80])
            v = self.get_feature()
            if v[1] == 0x80:
                return tuple(v[2:6])
            time.sleep(0.02)
        return (0, 0, 0, 0)

    def _detect(self):
        """ILM_RGBKB_Init — keyboard sub-type from usage page, FW version and EC 0x73C."""
        try:
            self.ver = self.firmware_version()
        except OSError as e:
            log.warning("ITE firmware version: %s", e)
        up, hi = self.usage_page, self.ver[0]
        kbid = self.ec.read(0x73C)
        # ILM_RGBKB_Init (checked in the IL): usage page FF02 -> type 4, FF12 -> four-zone keyboard (type 3 on
        # project 0x11, otherwise 2), FF03 -> per-key keyboards by firmware version and EC 0x73C.
        # (Up to 1.5.3 FF02 and FF12 were swapped here: MAIBENBEN Tsunami, ITE CE00 / FF12, is a four-zone keyboard.)
        t = 5
        if up == 0xFF02:
            t = 4
        elif up == 0xFF12:
            t = 3 if self.project == 0x11 else 2
        elif up == 0xFF03:
            if hi == 0x14:
                t = {0x39: 0xD, 0x31: 0xE, 0x79: 0xF, 0x71: 0x10}.get(kbid, 5)
            elif hi in (0x13, 0x16):
                t = {0x19: 7, 0x11: 8, 0x49: 9, 0x41: 0xA}.get(kbid, 5)
            elif hi == 0x12:
                t = 5 if kbid in (0x19, 0x29) else (6 if kbid in (0x11, 0x21) else 5)
            elif hi == 0x20:
                t = 0x12 if kbid == 0x18 else 0x11
        self.kb_type = t
        log.info("ITE keyboard %s pid=%04x usage=%s fw=%s type=%#x", self.node, self.pid,
                 hex(up) if up else None, ".".join(f"{x:X}" for x in self.ver), t)

    def four_zone(self):
        return self.kb_type in (2, 3)

    def fw_effects(self):
        hi, lo = self.ver[0], self.ver[1]
        return hi == 0x20 or (hi == 0x12 and lo >= 9) or hi == 0x14 or hi == 0x16

    # -- colour correction per keyboard type (WKDColor.cheatRGB_*) ----------------------
    def correct(self, r, g, b):
        if W is None:
            return (r, g, b)
        t = self.kb_type
        if t in (5, 6):
            return W.cheatRGB_2ndME(r, g, b)
        if t in ME_2P1ND:
            return W.cheatRGB_2p1ndME(r, g, b)
        if t in ME_2P2ND:
            return W.cheatRGB_2p2ndME(r, g, b)
        if t in (2, 3):
            return W.cheatRGB_4Zone(self.project, r, g, b)
        if t == 0xC:
            return W.cheatRGB_HIDLightbar(r, g, b)
        if t == 0x13:
            return W.cheatRGB_HIDLightbar2(r, g, b)
        if t == 0x14:
            return W.cheatRGB_HIDLightbar3(r, g, b)
        if t in (0x11, 0x12):
            return W.cheatRGB_HIDKeyboard3(r, g, b)
        return (r, g, b)

    def correct_user(self, r, g, b):
        """colour correction used by the 12h user-mode path"""
        if W is None:
            return (r, g, b)
        if self.kb_type in ME_2P2ND:
            return W.cheatRGB_2p2ndME(r, g, b)
        if self.kb_type in ME_3ND:
            return W.cheatRGB_HIDKeyboard3(r, g, b)
        return W.cheatRGB_2ndME(r, g, b)

    # -- picture (12h) ------------------------------------------------------------------
    @staticmethod
    def to_12h_order(buf):
        """ColorBufferConvertTo12H: 6x21 row-major (row 0 = top) -> column-major, bottom row first."""
        rows = [[buf[c + (5 - r) * COLS] for c in range(COLS)] for r in range(ROWS)]
        return [rows[r][c] for c in range(COLS) for r in range(ROWS)]

    def write_picture(self, colors, light, save=0, announce=True):
        """Set_ITE_Effect_Type_UserModeBy12H"""
        if announce:
            self.cmd08(2, 0x33, 0, light, 0, 0, save)
        seq = self.to_12h_order(colors)
        packets = []
        k = 0
        for _ in range(8):
            pkt = bytearray(0x41)
            for j in range(1, 0x41, 4):
                r, g, b = seq[k] if k < len(seq) else (0, 0, 0)
                r, g, b = self.correct_user(r, g, b)
                pkt[j:j + 4] = bytes((0, r, g, b))
                k += 1
            packets.append(pkt)
        self.cmd12(0)
        for p in packets:
            self.output(p)

    def write_static(self, rgb, light, save=0, announce=True):
        """Set_ITE_Effect_Type_StaticMode — whole keyboard one colour through 12h."""
        if announce:
            self.cmd08(2, 0x33, 0, light, 0, 0, save)
        r, g, b = self.correct(*rgb)
        pkt = bytearray(0x41)
        for j in range(1, 0x41, 4):
            pkt[j:j + 4] = bytes((0, r, g, b))
        self.cmd12(save)
        for _ in range(8):
            self.output(pkt)
            time.sleep(0.001)

    def write_rows(self, colors, light, save=0, announce=True):
        """Set_ITE_Effect_Type_UserMode — row protocol (B/G/R planes of 21 keys per row)."""
        if announce:
            self.cmd08(2, 0x33, 0, light, 0, 0, save)
        for row in range(ROWS):
            pkt = bytearray(0x41)
            for col in range(COLS):
                r, g, b = colors[col + (5 - row) * COLS]
                r, g, b = self.correct_user(r, g, b)
                pkt[2 + col], pkt[0x17 + col], pkt[0x2C + col] = b, g, r
            self.feature([0, 0x16, 0, row])
            self.output(pkt)

    def write_zones(self, cols, light, announce=False):
        """Four-zone keyboard: zone colours into palette slots 1..4 and the firmware static effect (colour arg 8)."""
        with self.lock:
            for i, (r, g, b) in enumerate(cols[:4]):
                self.cmd14(i + 1, r, g, b)
            if announce or getattr(self, "_zone_light", None) != light:
                self.cmd08(2, 0x01, 0, light, 8, 0, 0)
                self._zone_light = light
            else:
                self.cmd08(2, 0x01, 0, light, 8, 0, 0)

    # -- effects --------------------------------------------------------------------------
    def fw_mode(self, effect, light, speed, direction, colors, circular, ctrl=2):
        """Set_ITE_Effect_Type_FwMode"""
        flag = {0x21: 1, 0x22: 2, 0x23: 3}.get(ctrl, 0)
        color_arg = 0
        if colors:
            if circular:
                color_arg = 8
                for i, (r, g, b) in enumerate(colors):
                    self.cmd14(i + 1, r, g, b, flag)
            else:
                color_arg = 1
                self.cmd14(1, *colors[0], flag)
        if ctrl == 4:
            ctrl = 2
        self.cmd08(ctrl, effect, speed, light, color_arg, direction, 0)

    def fx(self):
        """the running BetterRGB effect engine, or None"""
        return self.ap if isinstance(self.ap, fxmod.FxEngine) else None

    def stop_ap(self):
        if self.ap:
            self.ap.stop()
            self.ap.join(timeout=2)
            self.ap = None

    def set_fx(self, idx, light=4, fx=None, force=False):
        """BetterRGB effect: the service draws every frame (see fx.py)"""
        want = dict(idx=idx, light=light, fx=fxmod.clean_params(idx, fx))
        now = time.monotonic()
        if want == self.saved and now - self._last_apply < REPEAT_WINDOW and not force:
            return
        had_ap = self.ap is not None
        self.stop_ap()
        lv = LIGHT[max(0, min(4, int(light)))]
        with self.lock:
            gap = max(MIN_GAP - (time.monotonic() - self._last_apply), 0.05 if had_ap else 0)
            if gap > 0:
                time.sleep(gap)
            self.cmd08(5)
            if self.four_zone():
                self.cmd08(1)
                time.sleep(0.03)
            self.ap = fxmod.FxEngine(self, idx, lv, want["fx"], self.fx_env)
            self.ap.start()
            self.saved = want
            self._last_apply = time.monotonic()

    def set_effect(self, idx, light=4, speed=2, direction=0, colors=None, circular=False, user=None, alphabet=None,
                   force=False, fx=None, untested=False):
        """ILM_RGBKB_SetEffectALL(mode=1) + Set_Lighting_Effect.
        untested: send an effect that the original window does not offer for this keyboard type (four-zone keyboards,
        light-bar effects on a keyboard) — the firmware draws it, ignores it or shows something else; nothing is
        stored in the controller, another effect brings it back. Music mode stays out (it needs audio capture)."""
        if fxmod.is_fx(idx):
            return self.set_fx(idx, light, fx, force)
        if idx not in EFFECTS:
            raise ValueError("unknown effect")
        code = EFFECTS[idx][1]
        if code == 0x22 or (code in LB_ONLY_EFFECTS and self.kb_type not in ME_LIGHTBAR and not untested):
            raise NotImplementedError("software effect")
        colors = [tuple(c) for c in (colors or [])]
        want = dict(idx=idx, light=light, speed=speed, direction=direction,
                    colors=colors, circular=circular, user=user, alphabet=alphabet)
        if untested:
            want["untested"] = True
        now = time.monotonic()
        if want == self.saved and now - self._last_apply < REPEAT_WINDOW and not force:
            log.debug("keyboard effect repeated within %.1f s — skipped", REPEAT_WINDOW)
            return
        had_ap = self.ap is not None
        self.stop_ap()
        lv, sp = LIGHT[max(0, min(4, light))], SPEED[max(0, min(4, speed))]
        dr = DIRECTION.get(direction, 1)
        if self.four_zone() and code not in FOUR_ZONE_EFFECTS | FOUR_ZONE_SOFT and not untested:
            raise ValueError("this effect is not available on a four-zone keyboard")
        with self.lock:
            gap = MIN_GAP - (time.monotonic() - self._last_apply)
            if had_ap:
                gap = max(gap, 0.05)
            if gap > 0:
                time.sleep(gap)
            self.cmd08(5)                      # ILM_RGBKB_SetEffectALL(mode 1): reset, then Set_Lighting_Effect
            if self.four_zone():
                # full stop between effects: on FF12 keyboards the firmware otherwise keeps parts of the previous
                # effect (palette slots, zones) when one effect follows another
                self.cmd08(1)
                time.sleep(0.03)
            if code == 0x01 and self.four_zone() and not circular:
                # one colour for every zone: the colour goes to all palette slots (a single slot = zone 1 only)
                self.fw_mode(code, lv, sp, dr, [(colors or [(255, 255, 255)])[0]] * 7, True)
            elif code == 0x01:
                # SetSingleEffect: firmware static effect on 0x12.9+/0x14/0x16/0x20, 4-zone and light bars,
                # otherwise a 12h picture of one colour (Set_ITE_Effect_Type_StaticMode)
                if self.fw_effects() or self.kb_type in (2, 3) or self.kb_type in ME_LIGHTBAR or not self.pictures_ok:
                    self.fw_mode(code, lv, sp, dr, colors or [(255, 255, 255)], False)
                else:
                    self.write_static(colors[0] if colors else (255, 255, 255), lv)
            elif code == 0x33:
                buf = [tuple(c) for c in (user or [])] + [(0, 0, 0)] * (ROWS * COLS)
                self.write_picture(buf[:ROWS * COLS], lv)
            elif code == 0x15:
                if self.fw_effects():
                    self.fw_mode(code, lv, sp, dr, colors, circular)
                else:
                    cols = (colors + DEFAULT_COLORS)[:4]
                    buf = [(0, 0, 0)] * (ROWS * COLS)
                    for i, k in enumerate((0x2D, 0x41, 0x42, 0x43)):   # SetGamingEffect: WASD + arrows
                        buf[k] = cols[i]
                    for i, k in enumerate((0x62, 0x76, 0x77, 0x78)):
                        buf[k] = cols[i]
                    self.write_rows(buf, lv)
            elif code == 0x34 and self.four_zone():
                self.ap = ZoneWave(self, lv, speed, reverse=dr == 2)
                self.ap.start()
            elif code == 0x03 and self.four_zone():
                # the firmware Wave on FF12 keyboards jumps from palette colour to palette colour; blend instead
                self.ap = ZoneWave(self, lv, speed, colors=colors if len(colors) > 1 else DEFAULT_COLORS,
                                   reverse=dr == 2)
                self.ap.start()
            elif code == 0x12 and self.four_zone():
                # Flash with fading instead of the hard on/off of the firmware
                self.ap = ZoneFlash(self, lv, speed, colors=colors if circular or colors else None)
                self.ap.start()
            elif code == 0x34:
                if self.ver[0] == 0x20:
                    self.fw_mode(0x22, lv, sp, dr, colors, circular, ctrl=7)
            elif code in AP_EFFECTS and apfx is None:
                raise ValueError("software effects need uwccd/lighting/oem (not installed)")
            elif code in AP_EFFECTS and not (code == 0x0D and self.kb_type in ME_LIGHTBAR):
                self.ap = APEngine(self, code, lv, sp, colors, alphabet)
                self.ap.start()
            else:
                if code == 5 and self.kb_type == 2:
                    for i, c in enumerate(((255, 0, 0), (0, 255, 0), (0, 0, 255), (255, 0, 255))):
                        self.cmd14(i + 1, *c)
                self.fw_mode(code, lv, sp, dr, colors, circular)
            if code in REACTIVE and dr == 1 and not self._onkey:
                try:
                    self.ec.set_bit(REG_ONKEY, ONKEY_BIT, True)
                    self._onkey = True
                    log.info("EC passes key presses to the keyboard (0x741 bit 3) for reactive effects")
                except Exception as e:  # noqa: BLE001
                    log.warning("EC 0x741: %s", e)
            self.saved = want
            self._last_apply = time.monotonic()

    def set_power(self, on):
        if not on and self.fx():
            self.ap.fade_out()       # the chosen transition backwards, then dark
        self.stop_ap()               # outside the lock: the frame thread may be waiting for it
        with self.lock:
            if not on:
                self.cmd08(5)
                self.cmd08(1)
                self._onkey = False          # Disable_EC_OnkeyPressed: set again with the next reactive effect
            elif self.saved:
                self.set_effect(**self.saved, force=True)
            else:
                self.set_effect(4)

    def set_brightness(self, light):
        """quick brightness change keeping the effect"""
        if self.saved:
            s = dict(self.saved)
            s["light"] = light
            self.set_effect(**s, force=True)

    def close(self):
        self.stop_ap()
        self.io.close()

    def info(self):
        return {"node": self.node, "pid": f"{self.pid:04X}", "fw": ".".join(f"{x:X}" for x in self.ver),
                "type": self.kb_type, "usage_page": self.usage_page, "fw_effects": self.fw_effects()}


