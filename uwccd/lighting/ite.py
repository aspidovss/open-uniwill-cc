"""ITE 829x per-key RGB keyboard controller (USB 048D:xxxx) — port of LightingModel.LM_ITE_RGB.

Protocol (HID feature reports, 9 bytes incl. report id 0):
  08h  [0,0x08,ctrl,effect,speed,light,color,direction,save]   ctrl: 1=off 2=effect 4=background 5=reset 6=zone
  09h  [0,0x09,0x02,level]                                      brightness
  12h  [0,0x12,0,0,0x08,..]                                      announce 8 picture rows (output reports, 65 bytes)
  14h  [0,0x14,flag,index,R,G,B,..]                              palette colour
  16h  [0,0x16,0,row]                                            row index (row protocol)
  80h  [0,0x80] -> get_feature: [_,0x80,hi,lo,test,customer]     firmware version
"""
