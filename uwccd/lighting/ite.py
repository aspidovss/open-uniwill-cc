def open_lightbar(ec, mock=False):
    if mock:
        return MockLightbar(ec)
    for d in find_devices(LB_PIDS):
        if (d["usage_page"] or 0) != 0xFF03:
            continue
        try:
            return ITELightbar(ec, d)
        except OSError as e:
            log.warning("cannot open light bar %s: %s", d["node"], e)
    return None


def list_devices():
    """All ITE (VID 048D) HID collections with their role — for diagnostics (uwccctl lighting)."""
    out = []
    for d in find_devices(None):
        role = "keyboard" if d["pid"] in KB_PIDS else "lightbar" if d["pid"] in LB_PIDS else "other"
        out.append({"node": d["node"], "pid": f"{d['pid']:04X}", "usage_page": f"{d['usage_page']:04X}" if d.get("usage_page") else None,
                    "role": role, "feature_len": d.get("feature_len"), "output_len": d.get("output_len")})
    return out


def open_keyboard(ec, mock=False):
    if mock:
        return MockITE(ec)
    devs = find_devices(KB_PIDS)
    # GCUService enumerates PIDs and takes the vendor collection (usage page 0xFFxx)
    devs.sort(key=lambda d: 0 if (d["usage_page"] or 0) >= 0xFF00 else 1)
    for d in devs:
        if (d["usage_page"] or 0) < 0xFF00:
            continue
        try:
            return ITEKeyboard(ec, d)
        except OSError as e:
            log.warning("cannot open %s: %s", d["node"], e)
    return None
