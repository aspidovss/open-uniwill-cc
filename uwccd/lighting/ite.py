LB_PIDS = [0x7000, 0x6005, 0x6008, 0x6010]

# LightingModel.RGBKB_Effect -> ITE effect code (Translate_ITE_EffectIndex)
EFFECTS = {
    0: ("Single", 0x01), 1: ("Breathing", 0x02), 2: ("Wave", 0x03), 3: ("Reactive", 0x04),
    4: ("Rainbow", 0x05), 5: ("Ripple", 0x06), 6: ("Raindrop", 0x0A), 7: ("Neon", 0x0F),
    8: ("Marquee", 0x09), 9: ("Stack", 0x0C), 10: ("Impact", 0x0D), 11: ("Spark", 0x11),
    12: ("Aurora", 0x0E), 13: ("Music", 0x22), 14: ("UserMode", 0x33), 15: ("Gaming", 0x15),
    16: ("Flash", 0x12), 17: ("Mix", 0x13), 18: ("RippleO", 0x16), 20: ("Alphabet", 0x17),
    21: ("StarHitting", 0x19), 22: ("StarSpark", 0x18), 23: ("Thinking", 0x21), 26: ("ColorfulWave", 0x34),
}
LIGHT = [0, 8, 0x16, 0x24, 0x32]          # Translate_ITE_LightValue (0..4)
SPEED = [0x0A, 7, 5, 3, 1]                # Translate_ITE_SpeedValue (0..4, slow..fast)
DIRECTION = {-1: 0, 0: 1, 1: 2, 2: 3, 3: 4, 4: 1, 5: 3}
DEFAULT_COLORS = [(255, 0, 0), (255, 165, 0), (255, 255, 0), (0, 255, 0), (0, 0, 255), (0, 127, 255), (139, 0, 255)]

# software-driven (AP) effects of GCUService (frames generated by the service, see apfx.py)
AP_EFFECTS = {0x0C, 0x0D, 0x0F, 0x17}
# lightbar-only AP effects (nothing is drawn on a keyboard by GCUService)
LB_ONLY_EFFECTS = {0x18, 0x19}

ME_3ND = {0x11, 0x12}
ME_2P1ND = {7, 8, 9, 0xA}
ME_2P2ND = {0xD, 0xE, 0xF, 0x10}
ME_LIGHTBAR = {0xC, 0x13, 0x14, 0x15}

ROWS, COLS = 6, 21


def _ioc(d, t, nr, size):
    return (d << 30) | (size << 16) | (ord(t) << 8) | nr


def HIDIOCSFEATURE(n):
    return _ioc(3, "H", 0x06, n)


def HIDIOCGFEATURE(n):
    return _ioc(3, "H", 0x07, n)


def _usage_page(desc):
    i = 0
    while i < len(desc):
        b = desc[i]
        size = {0: 0, 1: 1, 2: 2, 3: 4}[b & 3]
        if b & 0xFC == 0x04:  # Usage Page
            return int.from_bytes(desc[i + 1:i + 1 + size], "little")
        i += 1 + size
    return None


class HidrawTransport:
    """Linux /dev/hidrawN: feature reports via HIDIOC[SG]FEATURE, output reports via write()."""

    def __init__(self, dev):
        self.fd = os.open(dev["node"], os.O_RDWR | os.O_CLOEXEC)

    def feature(self, data):
        fcntl.ioctl(self.fd, HIDIOCSFEATURE(len(data)), bytes(data))

    def get_feature(self, size=9):
        buf = bytearray(size)
        fcntl.ioctl(self.fd, HIDIOCGFEATURE(size), buf, True)
        return buf

    def output(self, data):
        os.write(self.fd, bytes(data))

    def close(self):
        try:
            os.close(self.fd)
        except OSError:
            pass


def open_transport(dev):
    if sys.platform == "win32":
        from ..win.hid import WinHidTransport
        return WinHidTransport(dev)
    return HidrawTransport(dev)


def find_devices(pids):
    if sys.platform == "win32":
        from ..win.hid import enumerate_devices
        return enumerate_devices(VID, pids)
    out = []
    for hr in sorted(glob.glob("/sys/class/hidraw/hidraw*")):
        try:
            uevent = open(os.path.join(hr, "device", "uevent")).read()
        except OSError:
            continue
        hid_id = next((ln.split("=", 1)[1] for ln in uevent.splitlines() if ln.startswith("HID_ID=")), "")
        parts = hid_id.split(":")
        if len(parts) != 3:
            continue
        vid, pid = int(parts[1], 16), int(parts[2], 16)
        if vid != VID or (pids is not None and pid not in pids):
            continue
        try:
            desc = open(os.path.join(hr, "device", "report_descriptor"), "rb").read()
        except OSError:
            desc = b""
        out.append({"node": "/dev/" + os.path.basename(hr), "pid": pid, "usage_page": _usage_page(desc)})
    return out


class APEngine(threading.Thread):
    """LM_ITE_RGB.AP_Effect_Task — runs the generated frame program until stopped."""

    def __init__(self, kb, effect, light, speed, colors, alphabet):
        super().__init__(daemon=True, name="ap-effect")
        self.kb = kb
        self.effect, self.light, self.speed = effect, light, speed
        self.kb_type = kb.kb_type
        cols = list(colors or []) + DEFAULT_COLORS
        self.colors = [apfx.RGB(*c) for c in cols[:7]]
        self.alphabet = alphabet or "HELLO"
        self._halt = threading.Event()

    def stop(self):
        self._halt.set()

    def stopped(self):
        return self._halt.is_set()

    def sleep(self, ms):
        return not self._halt.wait(max(1, ms) / 1000.0)

    def user_mode(self, buf, first):
        if not self.stopped():
            self.kb.write_rows([c.t() for c in buf], self.light, 0, announce=bool(first))

    def static_mode(self, c, first):
        if not self.stopped():
            self.kb.write_static(c.t(), self.light, 0, announce=bool(first))

    def run(self):
        try:
            apfx.run(self)
        except OSError as e:
            log.warning("software effect stopped: %s", e)


class ITEKeyboard:
    def __init__(self, ec, dev):
        self.ec = ec
        self.node = dev["node"]
        self.pid = dev["pid"]
        self.usage_page = dev["usage_page"]
        self.io = open_transport(dev)
        self.lock = threading.RLock()
        self.project = ec.read(0x740)
        self.ver = (0, 0, 0, 0)
        self.kb_type = 0
        self.saved = None          # last effect (for power on)
        self.ap = None
        self._detect()

    # -- low level -------------------------------------------------------------------
    def feature(self, data):
        buf = bytes(data) + bytes(max(0, 9 - len(data)))
        if log.isEnabledFor(logging.DEBUG):
            log.debug("HID %04x feature %s", self.pid, buf.hex(" "))
        with self.lock:
            self.io.feature(buf)
        time.sleep(0.001)

    def get_feature(self):
        with self.lock:
            return self.io.get_feature(9)

    def output(self, data):
        if log.isEnabledFor(logging.DEBUG):
            log.debug("HID %04x output %d bytes %s…", self.pid, len(data), bytes(data[:16]).hex(" "))
        with self.lock:
            self.io.output(data)

    def cmd08(self, ctrl, effect=0, speed=0, light=0, color=0, direction=0, save=0):
        self.feature([0, 0x08, ctrl, effect, speed, light, color, direction, save])

    def cmd09(self, level):
        self.feature([0, 0x09, 0x02, level])

    def cmd12(self, save=0):
        self.feature([0, 0x12, 0, 0, 0x08, 0, 0, 0, save])

    def cmd14(self, index, r, g, b, flag=0, extra=0):
        r, g, b = self.correct(r, g, b)
        self.feature([0, 0x14, flag, index, r, g, b, extra, 0])

    def firmware_version(self):
        for _ in range(10):
            self.feature([0, 0x80])
            v = self.get_feature()
            if v[1] == 0x80:
                return tuple(v[2:6])
            time.sleep(0.02)
        return (0, 0, 0, 0)

    def _detect(self):
        """ILM_RGBKB_Init — keyboard sub-type from usage page, FW version and EC 0x73C."""
        try:
            self.ver = self.firmware_version()
        except OSError as e:
            log.warning("ITE firmware version: %s", e)
        up, hi = self.usage_page, self.ver[0]
        kbid = self.ec.read(0x73C)
        t = 5
        if up == 0xFF02:
            t = 3 if self.project == 0x11 else 2
        elif up == 0xFF03:
            t = 4
        elif up == 0xFF12:
            if hi == 0x14:
                t = {0x39: 0xD, 0x31: 0xE, 0x79: 0xF, 0x71: 0x10}.get(kbid, 5)
            elif hi in (0x13, 0x16):
                t = {0x19: 7, 0x11: 8, 0x49: 9, 0x41: 0xA}.get(kbid, 5)
            elif hi == 0x12:
                t = 5 if kbid in (0x19, 0x29) else (6 if kbid in (0x11, 0x21) else 5)
            elif hi == 0x20:
                t = 0x12 if kbid == 0x18 else 0x11
        self.kb_type = t
        log.info("ITE keyboard %s pid=%04x usage=%s fw=%s type=%#x", self.node, self.pid,
                 hex(up) if up else None, ".".join(f"{x:X}" for x in self.ver), t)

    def fw_effects(self):
        hi, lo = self.ver[0], self.ver[1]
        return hi == 0x20 or (hi == 0x12 and lo >= 9) or hi == 0x14 or hi == 0x16

    # -- colour correction per keyboard type (WKDColor.cheatRGB_*) ----------------------
    def correct(self, r, g, b):
        if W is None:
            return (r, g, b)
        t = self.kb_type
        if t in (5, 6):
            return W.cheatRGB_2ndME(r, g, b)
        if t in ME_2P1ND:
            return W.cheatRGB_2p1ndME(r, g, b)
        if t in ME_2P2ND:
            return W.cheatRGB_2p2ndME(r, g, b)
        if t in (2, 3):
            return W.cheatRGB_4Zone(self.project, r, g, b)
        if t == 0xC:
            return W.cheatRGB_HIDLightbar(r, g, b)
        if t == 0x13:
            return W.cheatRGB_HIDLightbar2(r, g, b)
        if t == 0x14:
            return W.cheatRGB_HIDLightbar3(r, g, b)
        if t in (0x11, 0x12):
            return W.cheatRGB_HIDKeyboard3(r, g, b)
        return (r, g, b)

    def correct_user(self, r, g, b):
        """colour correction used by the 12h user-mode path"""
        if W is None:
            return (r, g, b)
        if self.kb_type in ME_2P2ND:
            return W.cheatRGB_2p2ndME(r, g, b)
        if self.kb_type in ME_3ND:
            return W.cheatRGB_HIDKeyboard3(r, g, b)
        return W.cheatRGB_2ndME(r, g, b)

    # -- picture (12h) ------------------------------------------------------------------
    @staticmethod
    def to_12h_order(buf):
        """ColorBufferConvertTo12H: 6x21 row-major (row 0 = top) -> column-major, bottom row first."""
        rows = [[buf[c + (5 - r) * COLS] for c in range(COLS)] for r in range(ROWS)]
        return [rows[r][c] for c in range(COLS) for r in range(ROWS)]

    def write_picture(self, colors, light, save=0, announce=True):
        """Set_ITE_Effect_Type_UserModeBy12H"""
        if announce:
            self.cmd08(2, 0x33, 0, light, 0, 0, save)
        seq = self.to_12h_order(colors)
        packets = []
        k = 0
        for _ in range(8):
            pkt = bytearray(0x41)
            for j in range(1, 0x41, 4):
                r, g, b = seq[k] if k < len(seq) else (0, 0, 0)
                r, g, b = self.correct_user(r, g, b)
                pkt[j:j + 4] = bytes((0, r, g, b))
                k += 1
            packets.append(pkt)
        self.cmd12(0)
        for p in packets:
            self.output(p)

    def write_static(self, rgb, light, save=0, announce=True):
        """Set_ITE_Effect_Type_StaticMode — whole keyboard one colour through 12h."""
        if announce:
            self.cmd08(2, 0x33, 0, light, 0, 0, save)
        r, g, b = self.correct(*rgb)
        pkt = bytearray(0x41)
        for j in range(1, 0x41, 4):
            pkt[j:j + 4] = bytes((0, r, g, b))
        self.cmd12(save)
        for _ in range(8):
            self.output(pkt)
            time.sleep(0.001)

    def write_rows(self, colors, light, save=0, announce=True):
        """Set_ITE_Effect_Type_UserMode — row protocol (B/G/R planes of 21 keys per row)."""
        if announce:
            self.cmd08(2, 0x33, 0, light, 0, 0, save)
        for row in range(ROWS):
            pkt = bytearray(0x41)
            for col in range(COLS):
                r, g, b = colors[col + (5 - row) * COLS]
                r, g, b = self.correct_user(r, g, b)
                pkt[2 + col], pkt[0x17 + col], pkt[0x2C + col] = b, g, r
            self.feature([0, 0x16, 0, row])
            self.output(pkt)

    # -- effects --------------------------------------------------------------------------
    def fw_mode(self, effect, light, speed, direction, colors, circular, ctrl=2):
        """Set_ITE_Effect_Type_FwMode"""
        flag = {0x21: 1, 0x22: 2, 0x23: 3}.get(ctrl, 0)
        color_arg = 0
        if colors:
            if circular:
                color_arg = 8
                for i, (r, g, b) in enumerate(colors):
                    self.cmd14(i + 1, r, g, b, flag)
            else:
                color_arg = 1
                self.cmd14(1, *colors[0], flag)
        if ctrl == 4:
            ctrl = 2
        self.cmd08(ctrl, effect, speed, light, color_arg, direction, 0)

    def stop_ap(self):
        if self.ap:
            self.ap.stop()
            self.ap.join(timeout=2)
            self.ap = None

    def set_effect(self, idx, light=4, speed=2, direction=0, colors=None, circular=False, user=None, alphabet=None):
        """ILM_RGBKB_SetEffectALL(mode=1) + Set_Lighting_Effect"""
        if idx not in EFFECTS:
            raise ValueError("unknown effect")
        code = EFFECTS[idx][1]
        if code == 0x22 or (code in LB_ONLY_EFFECTS and self.kb_type not in ME_LIGHTBAR):
            raise NotImplementedError("software effect")
        self.stop_ap()
        lv, sp = LIGHT[max(0, min(4, light))], SPEED[max(0, min(4, speed))]
        dr = DIRECTION.get(direction, 1)
        colors = [tuple(c) for c in (colors or [])]
        with self.lock:
            self.cmd08(5)
            if code == 0x01:
                # GCUService draws "single colour" as a 12h picture unless the firmware is 0x12.9+/0x14/0x16/0x20;
                # ITE firmware 0x11 (e.g. MAIBENBEN Tsunami, project 0x10) ignores that picture but runs
                # every firmware effect, so it gets the firmware static effect too
                if self.fw_effects() or self.ver[0] == 0x11 or self.kb_type in (2, 3) or self.kb_type in ME_LIGHTBAR:
                    self.fw_mode(code, lv, sp, dr, colors or [(255, 255, 255)], False)
                else:
                    self.write_static(colors[0] if colors else (255, 255, 255), lv)
            elif code == 0x33:
                buf = [tuple(c) for c in (user or [])] + [(0, 0, 0)] * (ROWS * COLS)
                self.write_picture(buf[:ROWS * COLS], lv)
            elif code == 0x15:
                if self.fw_effects():
                    self.fw_mode(code, lv, sp, dr, colors, circular)
                else:
                    cols = (colors + DEFAULT_COLORS)[:4]
                    buf = [(0, 0, 0)] * (ROWS * COLS)
                    for i, k in enumerate((0x2D, 0x41, 0x42, 0x43)):   # SetGamingEffect: WASD + arrows
                        buf[k] = cols[i]
                    for i, k in enumerate((0x62, 0x76, 0x77, 0x78)):
                        buf[k] = cols[i]
                    self.write_rows(buf, lv)
            elif code == 0x34:
                if self.ver[0] == 0x20:
                    self.fw_mode(0x22, lv, sp, dr, colors, circular, ctrl=7)
            elif code in AP_EFFECTS and apfx is None:
                raise ValueError("software effects need uwccd/lighting/oem (not installed)")
            elif code in AP_EFFECTS and not (code == 0x0D and self.kb_type in ME_LIGHTBAR):
                self.ap = APEngine(self, code, lv, sp, colors, alphabet)
                self.ap.start()
            else:
                if code == 5 and self.kb_type == 2:
                    for i, c in enumerate(((255, 0, 0), (0, 255, 0), (0, 0, 255), (255, 0, 255))):
                        self.cmd14(i + 1, *c)
                self.fw_mode(code, lv, sp, dr, colors, circular)
            self.saved = dict(idx=idx, light=light, speed=speed, direction=direction,
                              colors=colors, circular=circular, user=user, alphabet=alphabet)

    def set_power(self, on):
        self.stop_ap()               # outside the lock: the frame thread may be waiting for it
        with self.lock:
            if not on:
                self.cmd08(5)
                self.cmd08(1)
            elif self.saved:
                self.set_effect(**self.saved)
            else:
                self.set_effect(4)

    def set_brightness(self, light):
        """quick brightness change keeping the effect"""
        if self.saved:
            s = dict(self.saved)
            s["light"] = light
            self.set_effect(**s)

    def close(self):
        self.stop_ap()
        self.io.close()

    def info(self):
        return {"node": self.node, "pid": f"{self.pid:04X}", "fw": ".".join(f"{x:X}" for x in self.ver),
                "type": self.kb_type, "usage_page": self.usage_page, "fw_effects": self.fw_effects()}


